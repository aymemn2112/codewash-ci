export const isLocaleSupported = (locale) => LOCALES.some((item) => item.id === locale);

export const interpolate = (template, vars = {}) =>
    template.replace(/\{(\w+)\}/g, (match, key) =>
        Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match,
    );

export const translate = (locale, key, vars) => {
    const dictionary = isLocaleSupported(locale)
        ? TRANSLATIONS[locale]
        : TRANSLATIONS[DEFAULT_LOCALE];
    const template = dictionary[key] ?? TRANSLATIONS[DEFAULT_LOCALE][key] ?? key;
    return interpolate(template, vars);
};
